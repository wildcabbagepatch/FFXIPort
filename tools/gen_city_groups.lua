-- Derives FFXIPort's same-city zone groups from LandSandBoat sources.
-- Usage: luajit tools/gen_city_groups.lua <lsb_root> [zones_yaml_dir]
--   <lsb_root> holds scripts/globals/homepoint.lua, src/map/utils/zoneutils.cpp,
--   data/enums/zone.yaml and data/zones/<name>/zone.yaml (flattened copies with
--   '/' replaced by '__' are accepted; zones_yaml_dir may hold <name>.yaml files).
--
-- Rule (docs/SERVER-MODULE.md "Same-city free travel"):
--   * A city is a non-zero LSB Home Point group (homepoint.lua `group`).
--   * A zone that hosts a Home Point (any entry in homepoint.lua, including
--     group 0 and entries LSB marks as not existing) belongs to that entry's
--     group, or to no city when the group is 0.
--   * A zone without any Home Point belongs to city G only if LSB marks it as
--     type `city` (zone.yaml) AND its conquest region (zoneutils.cpp
--     GetCurrentRegion) is the region of all of G's Home Point zones AND no
--     other city group has Home Points in that region.
-- Prints a Lua table literal and the evidence used.
-- GPL-3.0-only, (C) 2026 wildthing.
local lsb, zonesDir = arg[1], arg[2]
assert(lsb, 'usage: gen_city_groups.lua <lsb_root> [zones_yaml_dir]')

local function open(rel)
    for _, p in ipairs({ lsb .. '/' .. rel, lsb .. '/' .. rel:gsub('/', '__') }) do
        local f = io.open(p, 'r')
        if f then return f end
    end
    error('missing ' .. rel)
end

-- zone enum: snake name -> id
local zoneId, zoneName = {}, {}
for line in open('data/enums/zone.yaml'):lines() do
    local name, id = line:match('^%s+([%w_]+):%s+(%d+)')
    if name then zoneId[name] = tonumber(id); zoneName[tonumber(id)] = name end
end
local function squash(s) return (s:gsub('_', ''):lower()) end
local bySquash = {}
for name, id in pairs(zoneId) do bySquash[squash(name)] = id end

-- regions from GetCurrentRegion
local region, current = {}, {}
local inFn = false
for line in open('src/map/utils/zoneutils.cpp'):lines() do
    if line:find('auto GetCurrentRegion%(') then inFn = true
    elseif inFn then
        local z = line:match('case xi::ZoneId::(%w+):')
        if z then current[#current + 1] = z end
        local r = line:match('return xi::Region::(%w+);')
        if r then
            for _, cz in ipairs(current) do
                local id = bySquash[cz:lower()]
                if id then region[id] = r end
            end
            current = {}
        end
        if line:match('^}') then break end
    end
end

-- zone type flags
local function zoneTypes(name)
    local f = zonesDir and io.open(zonesDir .. '/' .. name .. '.yaml', 'r')
    if not f then
        local ok, g = pcall(open, 'data/zones/' .. name .. '/zone.yaml')
        f = ok and g or nil
    end
    if not f then return nil end
    for line in f:lines() do
        local t = line:match('^type:%s*%[(.-)%]')
        if t then f:close(); return t end
    end
    f:close()
    return ''
end

-- home points (raw LSB table, all entries)
local hpZoneGroup, groupZones = {}, {}
for line in open('scripts/globals/homepoint.lua'):lines() do
    local idx, g, zn = line:match('^%s+%[%s*(%d+)%] = { group = (%d+),.-xi%.zone%.([%w_]+)')
    if idx then
        local id = zoneId[zn:lower()]
        g = tonumber(g)
        hpZoneGroup[id] = hpZoneGroup[id] or g
        if g ~= 0 then
            groupZones[g] = groupZones[g] or {}
            groupZones[g][id] = true
        end
    end
end

local cityOf, evidence = {}, {}
local regionGroups = {}
for g, zones in pairs(groupZones) do
    local rs = {}
    for z in pairs(zones) do
        cityOf[z] = g
        rs[region[z] or '?'] = true
    end
    local n, only = 0, nil
    for r in pairs(rs) do n = n + 1; only = r end
    if n == 1 and only ~= '?' then
        regionGroups[only] = regionGroups[only] or {}
        regionGroups[only][#regionGroups[only] + 1] = g
        groupZones[g].region = only
    end
end

for id, r in pairs(region) do
    if hpZoneGroup[id] == nil then
        local groups = regionGroups[r]
        if groups and #groups == 1 then
            local t = zoneTypes(zoneName[id])
            if t and t:find('city') then
                cityOf[id] = groups[1]
                evidence[#evidence + 1] = string.format('-- zone %d %s: no Home Point, type [%s], region %s -> group %d',
                    id, zoneName[id], t, r, groups[1])
            end
        end
    end
end

local ids = {}
for id in pairs(cityOf) do ids[#ids + 1] = id end
table.sort(ids)
print('-- generated by tools/gen_city_groups.lua from LandSandBoat sources')
for _, e in ipairs(evidence) do print(e) end
print('{')
for _, id in ipairs(ids) do
    print(string.format('    [%3d] = %d, -- %s (%s)', id, cityOf[id], zoneName[id], region[id] or '?'))
end
print('}')

-- Optional check against the server module: arg[3] = repository root.
local repo = arg[3]
if repo then
    _G.Module = { new = function () return { addOverride = function () end } end }
    package.loaded['modules/module_utils'] = true
    _G.xi = { module = { registerCommand = function () end } }
    dofile(repo .. '/server/modules/custom/late/fpxport.lua')
    local mod, bad = xi.fpxport.cityGroupOfZone, 0
    for id, g in pairs(cityOf) do
        if mod[id] ~= g then bad = bad + 1; print(('MISMATCH zone %d: LSB-derived %d, module %s'):format(id, g, tostring(mod[id]))) end
    end
    for id, g in pairs(mod) do
        if cityOf[id] == nil then bad = bad + 1; print(('MISMATCH zone %d: module %d, not a city in LSB data'):format(id, g)) end
    end
    print(('city table check: %d zones, %d mismatches'):format(#ids, bad))
    os.exit(bad == 0 and 0 or 1)
end
